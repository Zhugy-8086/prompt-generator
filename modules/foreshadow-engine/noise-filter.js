// ==================== 伏笔引擎 - 噪音过滤 (noise-filter.js) ====================
// 挂载到 window.__ForeshadowNoiseFilter
// 过滤对话高频词、人名后缀、语气拟声词等

window.__ForeshadowNoiseFilter = (function() {

    var NOISE_WORDS = [
        '哈哈','呵呵','嘿嘿','嘻嘻','嗯嗯','哦哦','哎呀','哎哟','啊呀',
        '是吧','对吧','好吗','行吧','好的','是的','不是','没错',
        '咱','俺们','俺爹','俺娘','咋了','啥子','咱们','恁','咋地','怎么着',
        '师兄','师弟','师姐','师妹','师傅','师父','师叔','师伯',
        '道友','前辈','晚辈','阁下','大人','老爷','夫人','少爷','小姐',
        '这个','那个','那边','这边','那里','这里','这些','那些',
        '以前','以后','刚才','现在','待会','回头','等下',
        '走了','来了','去了','过来','过去','出去','进来','回去',
        '看看','听听','试试','想想','说说','问问',
        '嘛','呢','吧','呀','啊','哦','喂','嘞'
    ];

    // 非噪音例外列表：即使疑似人名也绝不误杀的词
    var NOISE_EXCEPTIONS = [
        '王座','将军','元帅','道士','黎明','和尚','圣旨','官银','邸报',
        '深渊','峡谷','云端','悬崖','城堡','洞穴','森林','海洋','河流',
        '旗帜','战场','牺牲','荣耀','背叛','忠诚','誓言','宿命','轮回',
        '神圣','降临','王权','神器','龙椅','宝座','太医','尚书','御史'
    ];

    function isNoiseWord(word) {
        // 先查例外列表
        if (NOISE_EXCEPTIONS.indexOf(word) !== -1) return false;
        // 再查噪音词表
        if (NOISE_WORDS.indexOf(word) !== -1) return true;
        // 纯姓 + 口语称呼后缀（老/小/哥/姐/叔/伯/婶/姨/弟/妹/爷/奶），长2字，判定为噪音；
        // 注意：普通双字人名（如“叶凡”“姬某”）不应被误杀
        if (/^[王姬李张刘陈杨赵黄周吴徐孙马胡朱郭何罗高林郑梁谢宋唐许邓韩冯曹彭曾肖田董潘袁蔡蒋余于杜叶程魏苏吕丁任卢姚沈钟姜崔谭廖范汪陆金石戴贾韦夏付方白邹孟熊秦邱江尹薛闫段雷侯龙史陶黎贺顾毛郝龚邵万钱严覃武戴莫孔向汤][老小哥姐叔伯婶姨弟妹爷奶]$/.test(word)) {
            return true;
        }
        return false;
    }

    return {
        isNoiseWord: isNoiseWord
    };
})();
